// 卡牌卡面图（2026 精选卡牌 终版 0521 校对版 / 印刷版）
// ──────────────────────────────────────────────────────────────
// 用途：游戏前端「查看卡牌」时，直接显示该卡的印刷版卡面图片。
//
// 图片由印刷版 PDF 逐页渲染而来（scripts/render_card_images.py），
// 命名为 public/cards-pdf/<card_code>.webp，由后端静态托管，
// 不依赖 OSS、不嵌 PDF（避免浏览器把 PDF 当附件下载）。
//
// 卡库内容已同步到 0521 终版，编号与卡面一一对应（E 系列统一两位 E01…E09）。

window.CARD_IMG_BASE = 'cards-pdf/';

// 拥有印刷版卡面图的 card_code 集合（45 张 2026 卡）
window.CARD_IMG_CODES = new Set([
  '2026B01', '2026B02', '2026B03', '2026B04', '2026B05', '2026B06', '2026B07', '2026B08', '2026B09',
  '2026P01', '2026P02', '2026P03', '2026P04', '2026P05', '2026P06', '2026P07', '2026P08', '2026P09',
  '2026S01', '2026S02', '2026S03', '2026S04', '2026S05', '2026S06', '2026S07', '2026S08', '2026S09',
  '2026E01', '2026E02', '2026E03', '2026E04', '2026E05', '2026E06', '2026E07', '2026E08', '2026E09',
  '2026D01', '2026D02', '2026D03', '2026D04', '2026D05', '2026D06', '2026D07', '2026D08', '2026D09'
]);

// 按 card_code 取卡面图 URL；没有则返回 null（回退为显示文字）。
window.getCardImage = function (cardCode) {
  if (!cardCode) return null;
  return window.CARD_IMG_CODES.has(cardCode)
    ? window.CARD_IMG_BASE + cardCode + '.webp'
    : null;
};
