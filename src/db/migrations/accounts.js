import {installOrganizationBindingUniqueness} from './organization-binding-uniqueness.js';
// No guessing historical ownership or converting production identities at boot.
// Explicit organization-entitlement migration also relaxes legacy fixed-seat checks.
import {installOrganizationEntitlements} from './organization-entitlements.js';
export async function migrateAccounts(tx) {
  await tx.get('SELECT pg_advisory_xact_lock(20261011, 6)');
  await tx.run('ALTER TABLE organizations ADD COLUMN IF NOT EXISTS location TEXT');
  await tx.run("INSERT INTO organizations(id,name,owner_user_id,status) VALUES(0,'通用组织',0,'active') ON CONFLICT(id) DO NOTHING");
  await tx.run(`CREATE TABLE IF NOT EXISTS identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone TEXT UNIQUE NOT NULL,
    username TEXT,
    password_hash TEXT,
    credential_version BIGINT NOT NULL DEFAULT 0,
    real_name TEXT,
    guardian_name TEXT,
    watcher_level TEXT NOT NULL DEFAULT 'initial',
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended')),
    trial_started_at BIGINT,
    trial_until BIGINT,
    created_at BIGINT NOT NULL,
    CHECK ((trial_started_at IS NULL AND trial_until IS NULL) OR trial_until > trial_started_at)
  )`);
  await tx.run(`CREATE TABLE IF NOT EXISTS subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
    plan TEXT NOT NULL CHECK (plan IN ('personal','group','city')),
    account_count INTEGER NOT NULL CHECK (account_count IN (1,5,20)),
    starts_at BIGINT NOT NULL,
    valid_until BIGINT NOT NULL CHECK (valid_until > starts_at),
    rebind_count INTEGER NOT NULL DEFAULT 0 CHECK (rebind_count BETWEEN 0 AND 2),
    created_at BIGINT NOT NULL,
    UNIQUE (id, organization_id),
    CHECK (account_count = CASE plan WHEN 'personal' THEN 1 WHEN 'group' THEN 5 ELSE 20 END)
  )`);
  await tx.run(`CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
    subscription_id BIGINT,
    name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'watcher' CHECK (role IN ('watcher','enterprise','boss','operator')),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended')),
    valid_until BIGINT,
    legacy_user_id BIGINT UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    created_at BIGINT NOT NULL,
    FOREIGN KEY (subscription_id, organization_id) REFERENCES subscriptions(id, organization_id) ON DELETE RESTRICT
  )`);
  await tx.run('CREATE UNIQUE INDEX IF NOT EXISTS subscriptions_one_per_organization ON subscriptions(organization_id)');
  await tx.run(`CREATE TABLE IF NOT EXISTS account_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
    identity_id BIGINT NOT NULL REFERENCES identities(id) ON DELETE RESTRICT,
    started_at BIGINT NOT NULL,
    ended_at BIGINT,
    CHECK (ended_at IS NULL OR ended_at >= started_at)
  )`);
  await tx.run('CREATE UNIQUE INDEX IF NOT EXISTS account_bindings_one_active ON account_bindings(account_id) WHERE ended_at IS NULL');
  await tx.run('CREATE INDEX IF NOT EXISTS account_bindings_identity ON account_bindings(identity_id) WHERE ended_at IS NULL');
  await tx.run(`CREATE OR REPLACE FUNCTION wqt_guard_subscription_capacity() RETURNS trigger AS $$
    DECLARE capacity INTEGER;
    BEGIN
      IF NEW.subscription_id IS NOT NULL THEN
        SELECT account_count INTO capacity FROM subscriptions WHERE id=NEW.subscription_id FOR UPDATE;
        IF (SELECT COUNT(*) FROM accounts WHERE subscription_id=NEW.subscription_id) >= capacity THEN
          RAISE EXCEPTION 'Subscription account capacity exceeded' USING ERRCODE='23514';
        END IF;
      END IF;
      RETURN NEW;
    END;
  $$ LANGUAGE plpgsql`);
  await tx.run('DROP TRIGGER IF EXISTS accounts_subscription_capacity ON accounts');
  await tx.run(`CREATE TRIGGER accounts_subscription_capacity BEFORE INSERT ON accounts
    FOR EACH ROW EXECUTE FUNCTION wqt_guard_subscription_capacity()`);
  await tx.run(`CREATE TABLE IF NOT EXISTS account_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id TEXT UNIQUE NOT NULL,
    operation TEXT NOT NULL,
    actor_identity_id BIGINT REFERENCES identities(id) ON DELETE RESTRICT,
    actor_account_id BIGINT REFERENCES accounts(id) ON DELETE RESTRICT,
    target_account_id BIGINT REFERENCES accounts(id) ON DELETE RESTRICT,
    subscription_id BIGINT REFERENCES subscriptions(id) ON DELETE RESTRICT,
    input_hash TEXT NOT NULL,
    result_json TEXT NOT NULL,
    created_at BIGINT NOT NULL
  )`);
  await tx.run('ALTER TABLE organizations ADD COLUMN IF NOT EXISTS owner_account_id BIGINT REFERENCES accounts(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE game_sessions ADD COLUMN IF NOT EXISTS account_id BIGINT REFERENCES accounts(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE game_sessions ADD COLUMN IF NOT EXISTS created_by_identity_id BIGINT REFERENCES identities(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE game_sessions ALTER COLUMN user_id DROP NOT NULL');
  await tx.run('CREATE INDEX IF NOT EXISTS game_sessions_account ON game_sessions(account_id, started_at DESC)');
  await tx.run('ALTER TABLE session_files ADD COLUMN IF NOT EXISTS uploaded_by_identity_id BIGINT REFERENCES identities(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE session_files ALTER COLUMN user_id DROP NOT NULL');
  await tx.run('ALTER TABLE identities ADD COLUMN IF NOT EXISTS credential_version BIGINT NOT NULL DEFAULT 0');
  await tx.run('ALTER TABLE identities ADD COLUMN IF NOT EXISTS trial_activated_at BIGINT');
  await tx.run('ALTER TABLE identities ADD COLUMN IF NOT EXISTS trial_granted_at BIGINT');
  await tx.run('ALTER TABLE identities ADD COLUMN IF NOT EXISTS trial_grant_consumed_at BIGINT');
  await tx.run('ALTER TABLE activities ADD COLUMN IF NOT EXISTS created_by_identity_id BIGINT REFERENCES identities(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE activities ADD COLUMN IF NOT EXISTS created_by_account_id BIGINT REFERENCES accounts(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS created_by_identity_id BIGINT REFERENCES identities(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS created_by_account_id BIGINT REFERENCES accounts(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE user_feedback ADD COLUMN IF NOT EXISTS identity_id BIGINT REFERENCES identities(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE user_feedback ADD COLUMN IF NOT EXISTS account_id BIGINT REFERENCES accounts(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE watcher_level_applications ADD COLUMN IF NOT EXISTS identity_id BIGINT REFERENCES identities(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE watcher_level_applications ADD COLUMN IF NOT EXISTS reviewed_by_identity_id BIGINT REFERENCES identities(id) ON DELETE RESTRICT');
  await tx.run("CREATE UNIQUE INDEX IF NOT EXISTS identity_one_pending_level_application ON watcher_level_applications(identity_id) WHERE status='pending' AND identity_id IS NOT NULL");
  await tx.run('ALTER TABLE watcher_level_logs ADD COLUMN IF NOT EXISTS identity_id BIGINT REFERENCES identities(id) ON DELETE RESTRICT');
  await tx.run('ALTER TABLE watcher_level_logs ADD COLUMN IF NOT EXISTS changed_by_identity_id BIGINT REFERENCES identities(id) ON DELETE RESTRICT');
  await tx.run(`CREATE OR REPLACE FUNCTION wqt_guard_account_ownership() RETURNS trigger AS $$
    BEGIN
      IF NEW.organization_id IS DISTINCT FROM OLD.organization_id OR
         NEW.subscription_id IS DISTINCT FROM OLD.subscription_id OR
         NEW.legacy_user_id IS DISTINCT FROM OLD.legacy_user_id THEN
        RAISE EXCEPTION 'Account ownership and entitlement association are immutable' USING ERRCODE='23514';
      END IF;
      RETURN NEW;
    END;
  $$ LANGUAGE plpgsql`);
  await tx.run('DROP TRIGGER IF EXISTS accounts_immutable_ownership ON accounts');
  await tx.run(`CREATE TRIGGER accounts_immutable_ownership BEFORE UPDATE OF organization_id, subscription_id, legacy_user_id ON accounts
    FOR EACH ROW EXECUTE FUNCTION wqt_guard_account_ownership()`);
  await tx.run(`CREATE OR REPLACE FUNCTION wqt_guard_session_account() RETURNS trigger AS $$
    BEGIN
      IF TG_OP = 'UPDATE' AND (NEW.account_id IS DISTINCT FROM OLD.account_id OR NEW.created_by_identity_id IS DISTINCT FROM OLD.created_by_identity_id) THEN
        RAISE EXCEPTION 'Session account and creator are immutable; reviewed migration required' USING ERRCODE='23514';
      END IF;
      IF NEW.account_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM accounts a WHERE a.id=NEW.account_id AND a.organization_id=NEW.organization_id) THEN
        RAISE EXCEPTION 'Session organization must match its account' USING ERRCODE='23514';
      END IF;
      IF TG_OP = 'INSERT' AND (NEW.account_id IS NULL OR NEW.created_by_identity_id IS NULL) THEN
        RAISE EXCEPTION 'New sessions require account and creator identity' USING ERRCODE='23514';
      END IF;
      RETURN NEW;
    END;
  $$ LANGUAGE plpgsql`);
  await tx.run('DROP TRIGGER IF EXISTS game_sessions_immutable_account ON game_sessions');
  await tx.run(`CREATE TRIGGER game_sessions_immutable_account BEFORE INSERT OR UPDATE OF account_id, created_by_identity_id, organization_id ON game_sessions
    FOR EACH ROW EXECUTE FUNCTION wqt_guard_session_account()`);
  await installOrganizationBindingUniqueness(tx);
  await installOrganizationEntitlements(tx);
}
