import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import bcrypt from 'bcryptjs';
import {startRuntime} from '../../../src/runtime.js';
import {dbRun,dbGet,withTransaction} from '../../../src/db.js';
import {cardsDbRun} from '../../../src/cards-db.js';
import {smsStore} from '../../../src/services/sms.js';
import {linkAutomaticActivity} from '../../../src/game/activities/link.js';

if(process.env.WQT_RUNTIME_TEST_CHILD!=='1') throw new Error('owned harness required');
export async function run(){
  let runtime;
  try {
    runtime=await startRuntime({port:0,host:'127.0.0.1'});
    const now=Date.now(), base=`http://127.0.0.1:${runtime.server.address().port}`;
    const phone='16600000710', password='SyntheticOnly!';
    const identity=(await dbRun('INSERT INTO identities(phone,password_hash,created_at) VALUES(?,?,?)',[phone,bcrypt.hashSync(password,10),now])).lastID;
    const other=(await dbRun("INSERT INTO identities(phone,created_at) VALUES('feedback-other',?)",[now])).lastID;
    const accounts=[], organizations=[];
    for(const n of [1,2]){
      const org=(await dbRun('INSERT INTO organizations(name,owner_user_id) VALUES(?,0)',[`test org ${n}`])).lastID;
      const id=(await dbRun('INSERT INTO accounts(organization_id,name,valid_until,created_at) VALUES(?,?,?,?)',[org,`test account ${n}`,now+86400000,now])).lastID;
      await dbRun('INSERT INTO account_bindings(account_id,identity_id,started_at) VALUES(?,?,?)',[id,identity,now]);
      accounts.push(id);organizations.push(org);
    }
    const group=(await cardsDbRun("INSERT INTO card_groups(name,released_ids_json,is_default,created_at) VALUES('test','[]',1,?)",[now])).lastID;
    const request=async(path,token,body,method=body?'POST':'GET')=>{
      const response=await fetch(base+path,{method,headers:{'content-type':'application/json',...(token?{authorization:`Bearer ${token}`}:{})},body:body?JSON.stringify(body):undefined});
      return {status:response.status,body:await response.json()};
    };
    smsStore.set(phone,{code:'111111',expiresAt:now+300000});
    const login=await request('/api/auth/login',null,{phone,password,code:'111111'});
    assert.equal(login.status,200,JSON.stringify(login));
    const tokens=[];
    for(const id of accounts){const result=await request('/api/auth/select-account',login.body.token,{accountId:id});assert.equal(result.status,200);tokens.push(result.body.token)}
    const input={location:'共享场地',cardGroupId:group,settings:{duration:300,counts:[1,0,0]}};
    const start=async(index,extra={})=>request('/api/player/start',tokens[index],{...input,requestId:randomUUID(),...extra});
    const first=await start(0);assert.equal(first.status,200,JSON.stringify(first));
    const parallel=await Promise.all(Array.from({length:8},(_,i)=>start(i%2)));
    assert.ok(parallel.every(r=>r.status===200),JSON.stringify(parallel));
    assert.ok(parallel.every(r=>r.body.activity.id===first.body.activity.id));
    assert.equal(new Set([first,...parallel].map(r=>r.body.activity.table_no)).size,9);
    const activity=await dbGet('SELECT * FROM activities WHERE id=?',[first.body.activity.id]);
    assert.equal(activity.enterprise_id,organizations[0]);
    assert.equal((await dbGet('SELECT organization_id FROM game_sessions WHERE id=?',[parallel[1].body.sessionId])).organization_id,organizations[1]);
    assert.equal((await request('/api/player/session/'+parallel[1].body.sessionId,tokens[0])).status,404,'activity membership grants no session access');
    const freshRace=await Promise.all(Array.from({length:8},(_,i)=>start(i%2,{location:'首次并发场地'})));
    assert.ok(freshRace.every(r=>r.status===200),JSON.stringify(freshRace));
    assert.equal(new Set(freshRace.map(r=>r.body.activity.id)).size,1);
    assert.equal(new Set(freshRace.map(r=>r.body.activity.table_no)).size,8);
    const winner=freshRace.find(r=>r.body.activity.table_no===1);
    const winnerSession=await dbGet('SELECT organization_id FROM game_sessions WHERE id=?',[winner.body.sessionId]);
    assert.equal((await dbGet('SELECT enterprise_id FROM activities WHERE id=?',[winner.body.activity.id])).enterprise_id,winnerSession.organization_id);
    assert.notEqual((await start(0,{location:'另一场地'})).body.activity.id,activity.id);
    const retry={...input,requestId:randomUUID()};
    const a=await request('/api/player/start',tokens[0],retry), b=await request('/api/player/start',tokens[0],retry);
    assert.equal(a.body.sessionId,b.body.sessionId);
    await dbRun("INSERT INTO activities(name,activity_code,status,enterprise_id) VALUES('独立活动','SEPARATE','active',?)",[organizations[0]]);
    const separate=await start(1,{activityCode:'SEPARATE'});assert.equal(separate.status,200);assert.notEqual(separate.body.activity.id,activity.id);
    const configuration={cardGroupId:group,mode:'standard',duration:300,counts:[1,0,0],ageRange:{min:8,max:12}};
    const creation={requestId:randomUUID(),name:'即时生效活动',location:'创建场地',started_at:now,configuration};
    const creations=await Promise.all(Array.from({length:6},()=>request('/api/activities/apply',tokens[0],creation)));
    assert.ok(creations.every(r=>r.status===200),JSON.stringify(creations));
    const created=creations[0].body;assert.equal(created.status,'active');assert.ok(creations.every(r=>r.body.id===created.id));
    const preset=await request('/api/activities/by-code/'+created.activity_code);
    assert.equal(preset.status,200);assert.deepEqual(JSON.parse(preset.body.activity.game_config_json),configuration);
    assert.equal((await dbGet('SELECT COUNT(*)::int AS n FROM activity_creation_notifications WHERE activity_id=?',[created.id])).n,1);
    assert.equal((await request('/api/activities/apply',tokens[0],{...creation,requestId:randomUUID(),configuration:{...configuration,ageRange:{min:14,max:8}}})).status,400);
    assert.equal((await start(0,{settings:{...input.settings,ageRange:{min:14,max:8}}})).status,400);
    const createdSession=await start(0,{activityCode:created.activity_code,settings:{...input.settings,ageRange:{min:8,max:12}}});assert.equal(createdSession.status,200);
    assert.deepEqual(JSON.parse((await dbGet('SELECT game_settings_json FROM game_sessions WHERE id=?',[createdSession.body.sessionId])).game_settings_json).ageRange,{min:8,max:12});
    assert.equal((await request('/api/admin/activities/notifications',tokens[0])).status,403);
    assert.equal((await request('/api/admin/activities/'+created.id,tokens[0],{requestId:randomUUID(),status:'ended'},'PUT')).status,403);
    const platformOrg=(await dbRun("INSERT INTO organizations(name,owner_user_id) VALUES('platform notification test',0)")).lastID;
    const boss=(await dbRun("INSERT INTO accounts(organization_id,name,role,created_at) VALUES(?,'boss','boss',?)",[platformOrg,now])).lastID;
    await dbRun('INSERT INTO account_bindings(account_id,identity_id,started_at) VALUES(?,?,?)',[boss,identity,now]);
    const bossToken=(await request('/api/auth/select-account',login.body.token,{accountId:boss})).body.token;
    const notifications=await request('/api/admin/activities/notifications',bossToken);assert.equal(notifications.status,200);assert.ok(notifications.body.notifications.some(n=>n.activity_id===created.id));
    const updated=await request('/api/admin/activities/'+created.id,bossToken,{requestId:randomUUID(),name:'管理员调整的活动',configuration:{...configuration,duration:600}},'PUT');assert.equal(updated.status,200,JSON.stringify(updated));
    assert.equal(JSON.parse((await request('/api/activities/by-code/'+created.activity_code)).body.activity.game_config_json).duration,600);
    assert.equal(JSON.parse((await dbGet('SELECT game_settings_json FROM game_sessions WHERE id=?',[createdSession.body.sessionId])).game_settings_json).duration,300,'template edits do not rewrite started sessions');
    assert.equal((await request('/api/admin/activities/'+created.id,bossToken,{requestId:randomUUID(),status:'ended'},'PUT')).status,200);
    assert.equal((await request('/api/activities/by-code/'+created.activity_code)).status,410);
    assert.equal((await start(0,{activityCode:created.activity_code})).status,404);
    const acknowledge={requestId:randomUUID()};
    assert.equal((await request('/api/admin/activities/'+created.id+'/acknowledge',bossToken,acknowledge)).status,200);
    assert.equal((await request('/api/admin/activities/'+created.id+'/acknowledge',bossToken,acknowledge)).status,200);
    assert.equal((await request('/api/admin/activities/notifications',bossToken)).body.notifications.length,0);
    await dbRun('UPDATE accounts SET valid_until=NULL WHERE id=?',[accounts[1]]);
    await dbRun('UPDATE identities SET trial_until=?,trial_started_at=? WHERE id=?',[now+86400000,now,identity]);
    assert.equal((await start(1)).status,200,'active trial can skip the code');
    await dbRun('UPDATE identities SET trial_started_at=?,trial_until=? WHERE id=?',[now-86400000,now-1,identity]);
    const before=(await dbGet('SELECT COUNT(*)::int AS n FROM game_sessions')).n;
    assert.equal((await start(1)).status,403);
    assert.equal((await dbGet('SELECT COUNT(*)::int AS n FROM game_sessions')).n,before);
    // UTC+8 midnight separates days; caller timestamps do not choose the HTTP matching day.
    const actor={id:accounts[0],identity_id:identity,organization_id:organizations[0]};
    const session={id:first.body.sessionId,account_id:accounts[0]};
    const day1=await withTransaction(tx=>linkAutomaticActivity(tx,session,actor,'边界测试',Date.parse('2026-10-20T15:59:59Z')));
    const day2=await withTransaction(tx=>linkAutomaticActivity(tx,session,actor,'边界测试',Date.parse('2026-10-20T16:00:00Z')));
    assert.notEqual(day1.id,day2.id);
    await dbRun("UPDATE activities SET status='ended' WHERE id=?",[activity.id]);
    const beforeEnded=(await dbGet('SELECT COUNT(*)::int AS n FROM game_sessions')).n;
    assert.equal((await start(0)).status,404,'ended canonical activity is not reopened');
    assert.equal((await dbGet('SELECT COUNT(*)::int AS n FROM game_sessions')).n,beforeEnded,'failed linking rolls back the new session');
    await dbRun("UPDATE activities SET status='active' WHERE id=?",[activity.id]);
    await dbRun('INSERT INTO user_feedback(identity_id,account_id,type,content) VALUES(?,?,?,?)',[identity,accounts[0],'suggestion','本人账号A']);
    await dbRun('INSERT INTO user_feedback(identity_id,account_id,type,content) VALUES(?,?,?,?)',[identity,accounts[1],'bug','本人账号B']);
    await dbRun('INSERT INTO user_feedback(identity_id,account_id,type,content) VALUES(?,?,?,?)',[other,accounts[0],'bug','其他身份']);
    await dbRun('INSERT INTO player_feedback(session_id,account_id,identity_id,questionnaire_json,answers_json,created_at) VALUES(?,?,?,?,?,?) RETURNING session_id',[first.body.sessionId,accounts[0],identity,'{"questions":[{"id":"q","label":"现场观察"}]}','{"q":"已提交答案"}',now]);
    const feedback=await request('/api/me/feedback',tokens[0]);assert.equal(feedback.status,200);
    assert.deepEqual(feedback.body.feedback.map(f=>f.content),['本人账号A']);
    assert.equal(feedback.body.surveys.length,1);
    assert.equal((await request('/api/me/feedback',tokens[1])).body.surveys.length,0);
    assert.equal((await request('/api/me/feedback')).status,401);
    await dbRun('UPDATE account_bindings SET ended_at=? WHERE identity_id=? AND account_id=?',[now,identity,accounts[0]]);
    assert.equal((await request('/api/me/feedback',tokens[0])).status,403);
    assert.equal((await start(0)).status,403);
    console.log(JSON.stringify({scoringActivityReview:true}));
  } finally {await runtime?.stop()}
}
