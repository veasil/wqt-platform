import assert from 'node:assert/strict';
import bcrypt from 'bcryptjs';
import jwt from 'jsonwebtoken';
import {createClient} from 'redis';
import {startRuntime} from '../../../src/runtime.js';
import {dbGet,dbRun} from '../../../src/db.js';
import {cardsDbRun,cardsDbGet} from '../../../src/cards-db.js';
import {smsStore} from '../../../src/services/sms.js';
import {closeIdentitySessions,initIdentitySessions,revokeIdentitySession} from '../../../src/services/identity-sessions.js';

if(process.env.WQT_RUNTIME_TEST_CHILD!=='1' || !process.env.WQT_REDIS_NAMESPACE?.startsWith('wqt_r1_')) throw new Error('owned PG/Redis test namespace required');
export async function run(){
  let runtime;
  const redis=createClient({url:process.env.REDIS_URL,socket:{reconnectStrategy:false}});
  redis.on('error',()=>{});
  const keys=[];
  try{
    await redis.connect();
    runtime=await startRuntime({port:0,host:'127.0.0.1'});
    const now=Date.now(),phone='16600000001',password='test-password';
    const identity=(await dbRun('INSERT INTO identities(phone,password_hash,guardian_name,created_at) VALUES(?,?,?,?)',[phone,bcrypt.hashSync(password,10),'Teacher',now])).lastID;
    const orgA=(await dbRun("INSERT INTO organizations(name,owner_user_id) VALUES('A',0)")).lastID;
    const orgB=(await dbRun("INSERT INTO organizations(name,owner_user_id) VALUES('B',0)")).lastID;
    const accounts=[];
    for(const org of [orgA,orgB]){
      const account=(await dbRun('INSERT INTO accounts(organization_id,name,valid_until,created_at) VALUES(?,?,?,?)',[org,`account-${org}`,now+86400000,now])).lastID;
      await dbRun('INSERT INTO account_bindings(account_id,identity_id,started_at) VALUES(?,?,?)',[account,identity,now]);
      accounts.push(account);
    }
    const unbound=(await dbRun("INSERT INTO accounts(organization_id,name,created_at) VALUES(?,'unbound',?)",[orgA,now])).lastID;
    const base=`http://127.0.0.1:${runtime.server.address().port}`;
    async function request(path,token=null,body=null,method=body?'POST':'GET'){
      const response=await fetch(base+path,{method,headers:{...(token?{authorization:`Bearer ${token}`}:{ }),'content-type':'application/json'},body:body?JSON.stringify(body):undefined});
      return {status:response.status,body:await response.json()};
    }
    async function login(){
      smsStore.set(phone,{code:'111111',expiresAt:Date.now()+300000});
      const response=await request('/api/auth/login',null,{phone,password,code:'111111'});
      assert.equal(response.status,200,JSON.stringify(response));
      return response.body;
    }
    const key=`${process.env.WQT_REDIS_NAMESPACE}:identity-session:${identity}`;
    keys.push(key);
    const initial=await login();
    await dbRun("INSERT INTO activities(name,organizer,activity_code,status,enterprise_id) VALUES('组织活动','合成地点','ORGACT','active',?)",[orgA]);
    await dbRun("INSERT INTO activities(name,organizer,activity_code,status) VALUES('通用活动','合成地点','GENERALACT','active')");
    const resolved=await request('/api/auth/activity-account/ORGACT',initial.token);
    assert.equal(resolved.status,200);
    assert.deepEqual(resolved.body.accounts.map(a=>a.id),[accounts[0]]);
    await dbRun("UPDATE accounts SET role='enterprise' WHERE id=?",[accounts[0]]);
    assert.deepEqual((await request('/api/auth/activity-account/ORGACT',initial.token)).body.accounts.map(a=>a.id),[accounts[0]],'organization administrators play through the same account');
    await dbRun("UPDATE accounts SET role='watcher' WHERE id=?",[accounts[0]]);
    assert.equal((await request('/api/auth/activity-account/ORGACT')).status,401);
    assert.equal((await request('/api/auth/activity-account/GENERALACT',initial.token)).body.code,'ACTIVITY_ORGANIZATION_REQUIRED');
    assert.equal((await request('/api/auth/activity-account/UNKNOWN',initial.token)).status,404);
    assert.equal(initial.requiresAccountSelection,true);
    assert.equal(initial.accounts.length,2);
    assert.equal((await request('/api/me',initial.token)).body.code,'ACCOUNT_REQUIRED');
    assert.equal((await request('/api/auth/select-account',initial.token,{accountId:unbound})).status,403);
    const selectedA=await request('/api/auth/select-account',initial.token,{accountId:accounts[0]});
    assert.equal(selectedA.status,200);
    const A=selectedA.body.token;
    assert.equal((await request('/api/cards/study',A)).status,200);
    await dbRun('UPDATE accounts SET valid_until=NULL WHERE id=?',[accounts[0]]);
    await dbRun('UPDATE identities SET trial_started_at=?,trial_until=? WHERE id=?',[now,now+86400000,identity]);
    assert.equal((await request('/api/cards/study',A)).status,403,'trial alone is not paid study access');
    await dbRun('UPDATE accounts SET valid_until=? WHERE id=?',[now+86400000,accounts[0]]);
    const selectedB=await request('/api/auth/select-account',initial.token,{accountId:accounts[1]});
    assert.equal(selectedB.status,200);
    const B=selectedB.body.token;
    assert.equal(jwt.decode(A).jti,jwt.decode(B).jti);
    assert.equal(jwt.decode(A).exp,jwt.decode(initial.token).exp);
    const reads=await Promise.all(Array.from({length:20},()=>request('/api/me',A)));
    assert.ok(reads.every(result=>result.status===200));
    assert.equal(JSON.parse(await redis.get(key)).expiresAt,initial.expiresAt);
    const game=await request('/api/game/start',A,{requestId:'auth-game-start-test',accountId:accounts[1],ts:now});
    const levelRequests=await Promise.all(Array.from({length:6},()=>request('/api/me/level-application',A,{reason:'experience'})));
    assert.equal(levelRequests.filter(result=>result.status===200).length,1);
    assert.equal(levelRequests.filter(result=>result.status===409).length,5);
    const applicationA=await request('/api/me/level-application',A);
    const applicationB=await request('/api/me/level-application',B);
    assert.equal(applicationA.body.application.id,applicationB.body.application.id);
    assert.equal((await request('/api/me/feedback',B,{content:'cross-account',session_id:game.body.sessionId})).status,404);
    assert.equal((await request('/api/me/feedback',A,{content:'own-feedback',session_id:game.body.sessionId})).status,200);
    assert.equal(game.status,200,JSON.stringify(game));
    const session=await dbGet('SELECT * FROM game_sessions WHERE id=?',[game.body.sessionId]);
    assert.equal(session.account_id,accounts[0]);
    assert.equal((await request(`/api/game/session/${session.id}`,B)).status,404);
    await dbRun('UPDATE account_bindings SET ended_at=? WHERE account_id=? AND ended_at IS NULL',[Date.now(),accounts[0]]);
    assert.deepEqual((await request('/api/auth/activity-account/ORGACT',initial.token)).body.accounts,[],'an activity code cannot restore revoked membership');
    assert.equal((await request(`/api/game/session/${session.id}`,A)).status,403);
    assert.equal((await request('/api/me',B)).status,200);
    const replacement=await login();
    assert.equal(replacement.requiresAccountSelection,false);
    assert.equal((await request('/api/me',B)).status,401);
    await revokeIdentitySession(identity,jwt.decode(B).jti);
    assert.equal((await request('/api/me',replacement.token)).status,200);
    const record=JSON.parse(await redis.get(key));
    await redis.set(key,JSON.stringify({...record,expiresAt:Date.now()-1}));
    assert.equal((await request('/api/me',replacement.token)).status,401);
    const current=await login();
    await closeIdentitySessions();
    assert.equal((await request('/api/me',current.token)).status,503);
    await initIdentitySessions();
    assert.equal((await request('/api/me',current.token)).status,200);
    await dbRun('UPDATE identities SET credential_version=credential_version+1 WHERE id=?',[identity]);
    assert.equal((await request('/api/me',current.token)).status,401);
    const beforePhoneChange=await login();
    const bossPhone='16600000002';
    const bossIdentity=(await dbRun('INSERT INTO identities(phone,password_hash,guardian_name,created_at) VALUES(?,?,?,?)',[bossPhone,bcrypt.hashSync(password,10),'Boss',now])).lastID;
    const bossAccount=(await dbRun("INSERT INTO accounts(organization_id,name,role,created_at) VALUES(0,'platform','boss',?)",[now])).lastID;
    await dbRun('INSERT INTO account_bindings(account_id,identity_id,started_at) VALUES(?,?,?)',[bossAccount,bossIdentity,now]);
    keys.push(`${process.env.WQT_REDIS_NAMESPACE}:identity-session:${bossIdentity}`);
    smsStore.set(bossPhone,{code:'111111',expiresAt:Date.now()+300000});
    const bossLogin=await request('/api/auth/admin-login',null,{phone:bossPhone,password,code:'111111'});
    assert.equal(bossLogin.status,200);
    const newPhone='16600000003';
    const phoneChange={requestId:'auth-phone-change-test',identityId:identity,newPhone,smsCode:'111111',verificationNote:'Verified same person; old phone unavailable'};
    assert.equal((await request('/api/admin/identities/change-phone',beforePhoneChange.token,phoneChange)).status,403);
    smsStore.set(newPhone,{code:'111111',expiresAt:Date.now()+300000});
    const changed=await request('/api/admin/identities/change-phone',bossLogin.body.token,phoneChange);
    assert.equal(changed.status,200,JSON.stringify(changed));
    assert.equal(changed.body.identityId,identity);
    assert.equal(await redis.get(key),null);
    assert.equal((await request('/api/me',beforePhoneChange.token)).status,401);
    smsStore.set(newPhone,{code:'111111',expiresAt:Date.now()+300000});
    const newLogin=await request('/api/auth/login',null,{phone:newPhone,password,code:'111111'});
    assert.equal(newLogin.status,200);
    assert.equal(newLogin.body.user.identityId,identity);
    assert.equal(newLogin.body.user.guardianName,'Teacher');
    assert.equal(newLogin.body.user.accountId,accounts[1]);
    assert.equal((await request('/api/me',newLogin.body.token)).status,200);
    const phoneReplay=await request('/api/admin/identities/change-phone',bossLogin.body.token,phoneChange);
    assert.equal(phoneReplay.status,200,'phone change replays without fresh SMS');
    assert.equal((await request('/api/me',newLogin.body.token)).status,200,'replay must preserve the newer credential session');
    assert.equal((await dbGet("SELECT COUNT(*)::int AS count FROM account_operations WHERE operation='change-phone'")).count,1);
    assert.equal((await request('/api/admin/users',bossLogin.body.token)).status,404,'legacy person mutation surface must not be mounted in account mode');
    const legacyCard=(await cardsDbRun("INSERT INTO cards(key,safety_type,event,options_json,author_id) VALUES(991001,'physical','legacy','{}',?)",[identity])).lastID;
    await cardsDbRun("INSERT INTO card_versions(card_id,key,safety_type,event,options_json,author_id) VALUES(?,991001,'physical','legacy','{}',?)",[legacyCard,identity]);
    const hiddenVersions=await request(`/api/admin/cards/${legacyCard}/versions`,newLogin.body.token);
    assert.equal(hiddenVersions.status,200);
    assert.equal(hiddenVersions.body.versions.length,0,'coincident identity/users IDs must never confer legacy authorship');
    const newCard=await request('/api/cards',bossLogin.body.token,{key:991002,safetyType:'physical',phase:'启蒙期',event:'new identity author',options:{},status:'active'});
    assert.equal(newCard.status,200,JSON.stringify(newCard));
    const cardAuthor=await cardsDbGet('SELECT author_id,author_identity_id FROM cards WHERE id=?',[newCard.body.id]);
    assert.equal(cardAuthor.author_id,null);
    assert.equal(cardAuthor.author_identity_id,bossIdentity);
    const group=await request('/api/admin/card-groups',bossLogin.body.token,{name:'identity-author-group',card_ids:[newCard.body.id]});
    assert.equal(group.status,200,JSON.stringify(group));
    const groupAuthor=await cardsDbGet('SELECT created_by,created_by_identity_id FROM card_groups WHERE id=?',[group.body.id]);
    assert.equal(groupAuthor.created_by,null);
    assert.equal(groupAuthor.created_by_identity_id,bossIdentity);
    const published=await request(`/api/admin/cards/${newCard.body.id}/release`,bossLogin.body.token,{});
    assert.equal(published.status,200,JSON.stringify(published));
    const publisher=await cardsDbGet('SELECT released_by,released_by_identity_id FROM cards_released WHERE card_id=? ORDER BY id DESC LIMIT 1',[newCard.body.id]);
    assert.equal(publisher.released_by,null);
    assert.equal(publisher.released_by_identity_id,bossIdentity);
    console.log(JSON.stringify({redisSession:true,parallelReads:true,bindingRevocation:true}));
  }finally{
    if(runtime)await runtime.stop();
    if(redis.isReady && keys.length)await redis.del(keys);
    if(redis.isOpen)redis.destroy();
  }
}
